"""Generate crates/hud/src/model/palette.rs: color names and palettes of the reference.

The names and the two palettes are the contract that makes `[grey50]` and the 256/16 color
downgrade byte-identical to Rich, so they are extracted as data from the pinned Rich (see
THIRD_PARTY_NOTICES.md and DEVIATIONS.md D-030). No code is copied.
"""

import importlib.metadata as md
import sys
from pathlib import Path

from rich.color import ANSI_COLOR_NAMES, EIGHT_BIT_PALETTE, STANDARD_PALETTE

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "crates" / "hud" / "src" / "model" / "palette.rs"


def triples(palette):
    return [tuple(c) for c in palette._colors]


def main():
    rich_version = md.version("rich")
    names = sorted(ANSI_COLOR_NAMES.items())
    standard = triples(STANDARD_PALETTE)
    eight = triples(EIGHT_BIT_PALETTE)
    assert len(standard) == 16 and len(eight) == 256
    lines = [
        "// @generated by bench/scripts/gen_palette.py. Do not edit.",
        f"// Data extracted from Rich {rich_version} (MIT License, Copyright (c) 2020 Will McGugan):",
        "// the 235 color names with their palette numbers and the two palettes used for color",
        "// downgrade. The notice is reproduced in THIRD_PARTY_NOTICES.md.",
        "",
        "//! Color names and palettes.",
        "",
        "/// Color names with their 8-bit palette number, sorted by name for binary search.",
        f"pub(crate) const NAMES: [(&str, u8); {len(names)}] = [",
    ]
    lines += [f'    ("{name}", {number}),' for name, number in names]
    lines += [
        "];",
        "",
        "/// RGB values the 16 standard colors are matched against when downgrading.",
        "pub(crate) const STANDARD: [(u8, u8, u8); 16] = [",
    ]
    lines += [f"    ({r}, {g}, {b})," for r, g, b in standard]
    lines += [
        "];",
        "",
        "/// RGB values of the 256-color palette.",
        "pub(crate) const EIGHT_BIT: [(u8, u8, u8); 256] = [",
    ]
    lines += [f"    ({r}, {g}, {b})," for r, g, b in eight]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(names)} names", file=sys.stderr)


if __name__ == "__main__":
    main()
