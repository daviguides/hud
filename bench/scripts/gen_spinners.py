"""Generates crates/hud/src/model/spinners.rs from the animations of the pinned Python Rich.

The 73 spinners are data (names, intervals, frame sequences). They originate in the `cli-spinners`
project (MIT) and reach hud through Rich (MIT); both notices are in THIRD_PARTY_NOTICES.md. Python
indexes a string of frames by code point, so a spinner whose frames are one string is split into
code points here, exactly as Rich indexes it. Deterministic: a clean tree shows no diff.

Usage: gen_spinners.py [--check]   (--check compares the generated table with Rich and the file)
"""

import sys
from importlib.metadata import version
from pathlib import Path

from rich._spinners import SPINNERS

OUT = Path(__file__).resolve().parents[2] / "crates" / "hud" / "src" / "model" / "spinners.rs"


def literal(text):
    out = []
    for ch in text:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch.isprintable() and ch != "​":
            out.append(ch)
        else:
            out.append(f"\\u{{{ord(ch):x}}}")
    return '"' + "".join(out) + '"'


def frames_of(spinner):
    frames = spinner["frames"]
    return list(frames) if isinstance(frames, str) else [str(f) for f in frames]


def render():
    lines = [
        f"//! The animations of Rich {version('rich')}: names, frame sequences and intervals.",
        "//!",
        "//! Generated by `bench/scripts/gen_spinners.py` from the pinned Python Rich; do not edit. The",
        "//! frames originate in the `cli-spinners` project (MIT), through Rich (MIT); see",
        "//! `THIRD_PARTY_NOTICES.md`.",
        "",
        "/// One animation: its name, the milliseconds a frame lasts and its frames.",
        "#[derive(Debug)]",
        "pub(crate) struct SpinnerData {",
        "    pub(crate) name: &'static str,",
        "    pub(crate) interval: f64,",
        "    pub(crate) frames: &'static [&'static str],",
        "}",
        "",
        "#[rustfmt::skip]",
        "pub(crate) const SPINNERS: &[SpinnerData] = &[",
    ]
    for name in sorted(SPINNERS):
        spinner = SPINNERS[name]
        frames = ", ".join(literal(f) for f in frames_of(spinner))
        lines.append(f"    SpinnerData {{ name: {literal(name)}, interval: {float(spinner['interval'])!r}, frames: &[{frames}] }},")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        ok = OUT.read_text() == text
        print(f"{len(SPINNERS)} spinners, file {'matches' if ok else 'DIFFERS from'} the generator")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print(f"{len(SPINNERS)} spinners written to {OUT}")


if __name__ == "__main__":
    main()
